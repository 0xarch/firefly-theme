#!/usr/bin/env bun
/**
 * Resolve the icon references declared in `partial/icon.ejs` into drawing data
 * and write `partial/icon-svg.ejs`.
 *
 * The theme renders through EJS templates, which have no module loader, so the
 * iconify packs cannot be read at render time: they are a *build-time* input.
 * `partial/icon.ejs` stays the source of truth for names (and is the only file
 * a maintainer edits); this script only turns `collection:icon` references into
 * the inline SVG bodies the templates need.
 *
 *   bun install    # once
 *   bun run icons  # after adding/removing a name in partial/icon.ejs
 */
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const sourceUrl = new URL("partial/icon.ejs", root);
const targetUrl = new URL("partial/icon-svg.ejs", root);

const MANIFEST = /const ICON_MANIFEST = \{([\s\S]*?)\n\};/;
const ENTRY = /^\s*["']?([A-Za-z0-9_-]+)["']?:\s*"([^"]+)",\s*$/;

const source = readFileSync(sourceUrl, "utf8");
const block = source.match(MANIFEST);
if (!block) throw new Error(`${sourceUrl.pathname}: no ICON_MANIFEST block found`);

const entries = block[1]
  .split("\n")
  .map((line) => line.match(ENTRY))
  .filter(Boolean)
  .map((m) => ({ name: m[1], ref: m[2] }));
if (entries.length === 0) throw new Error(`${sourceUrl.pathname}: ICON_MANIFEST is empty`);

/** group the requested icons by collection so each pack is read once */
const wanted = new Map();
for (const { name, ref } of entries) {
  const [pack, icon] = ref.split(":");
  if (!pack || !icon) {
    throw new Error(`icon "${name}" has a bad reference "${ref}" (expected collection:icon)`);
  }
  if (!wanted.has(pack)) wanted.set(pack, []);
  wanted.get(pack).push({ name, icon });
}

const resolved = {};
for (const [pack, icons] of wanted) {
  const path = new URL(`node_modules/@iconify-json/${pack}/icons.json`, root);
  let data;
  try {
    data = JSON.parse(readFileSync(path, "utf8"));
  } catch {
    throw new Error(`cannot read @iconify-json/${pack} — run \`bun install\` first`);
  }
  // aliases point at another icon in the same pack
  const find = (icon, seen = new Set()) => {
    if (data.icons[icon]) return data.icons[icon];
    const alias = data.aliases && data.aliases[icon];
    if (alias && alias.parent && !seen.has(icon)) {
      seen.add(icon);
      return find(alias.parent, seen);
    }
    return null;
  };
  // the grid size is usually declared once per pack (material-symbols: 24,
  // font awesome: 640); an icon may override it
  const width = data.width ?? 24;
  const height = data.height ?? 24;
  for (const { name, icon } of icons) {
    const data_ = find(icon);
    if (!data_) throw new Error(`@iconify-json/${pack} has no icon "${icon}" (name: ${name})`);
    resolved[`${pack}:${icon}`] = {
      w: data_.width ?? width,
      h: data_.height ?? height,
      x: data_.left ?? 0,
      y: data_.top ?? 0,
      b: data_.body,
    };
  }
}

const rows = Object.entries(resolved)
  .map(([ref, icon]) =>
    `  ${JSON.stringify(ref)}: { w: ${icon.w}, h: ${icon.h}, x: ${icon.x}, y: ${icon.y}, b: ${JSON.stringify(icon.b)} },`)
  .join("\n");

const generated = `<%
/* ==========================================================================
   Icon drawing data — GENERATED by scripts/build-icons.mjs. Do not edit:
   the names and their iconify references live in partial/icon.ejs.

   Refresh after changing that manifest:  bun run icons

   Expects { ref, size, extraClass } from partial/icon.ejs.
   ========================================================================== */
const DATA = {
${rows}
};
const drawing = DATA[ref];
const px = (typeof size !== "undefined" && size) ? size : 20;
const klass = (typeof extraClass !== "undefined" && extraClass) ? " " + extraClass : "";
%>
<% if (drawing) { %><svg class="icon<%= klass %>" width="<%= px %>" height="<%= px %>" viewBox="<%= drawing.x %> <%= drawing.y %> <%= drawing.w %> <%= drawing.h %>" fill="currentColor" aria-hidden="true" focusable="false"><%- drawing.b %></svg><% } %>
`;

writeFileSync(targetUrl, generated);
console.log(`icons: ${Object.keys(resolved).length} written to ${targetUrl.pathname.slice(root.pathname.length)}`);
